// Builds gamedata/scripts/persistent_stalkers_lobby_known.script: the script
// names a lobby game always starts (AGENTS.md, "The lobby", "Scripts not started").
//
//   base   Anomaly 1.5.3's own scripts (scripts.db0, unpacked): a mod's copy of
//          a base script still runs
//   loose  the scripts loose in the game's gamedata (the modded exes, xrRazom,
//          what G.A.M.M.A. installs there); xrr_* is kept by prefix and left out
//
// The lobby works out the rest in game: every script the engine lists that is
// on neither list, nor kept by prefix, is not started. So this file depends on
// the game's version and the modded exes, not on a player's mod list. It is in
// git; run this again only after an Anomaly or modded exes update.
//
// Run:  node tools/build_known_scripts.js [anomaly dir] [unpacked base scripts]
'use strict';
const fs = require('fs');
const path = require('path');

const repo = path.resolve(__dirname, '..');
const anomaly = process.argv[2] || 'D:/Anomaly';
const baseDir = process.argv[3] || path.resolve(repo, '..', 'Lobby_spawn', 'anomaly_db', 'scripts');

function scripts(dir) {
  if (!fs.existsSync(dir)) {
    console.error(`no folder ${dir}${dir === baseDir ? `\n(converter.exe -unpack -xdb ${anomaly}\\db\\configs\\scripts.db0 -dir <dir>)` : ''}`);
    process.exit(1);
  }
  return fs.readdirSync(dir).filter(f => /\.script$/i.test(f)).map(f => f.toLowerCase()).sort();
}

const base = scripts(baseDir);
const baseSet = new Set(base);
const loose = scripts(path.join(anomaly, 'gamedata', 'scripts')).filter(f => !f.startsWith('xrr_') && !baseSet.has(f));

const EOL = '\r\n';
const list = (name, items) => [`${name} = {`, ...items.map(n => `\t["${n}"] = true,`), '}'];
const out = [
  '-- Generated by tools/build_known_scripts.js: do not edit. The scripts a lobby',
  '-- game always starts (persistent_stalkers_lobby_boot.skip_names): Anomaly\'s own',
  '-- and those loose in the game\'s gamedata (the modded exes, xrRazom; xrr_* is',
  '-- kept by prefix). Depends on the game\'s version, not on the mod list.',
  `-- ${base.length} base, ${loose.length} loose.`,
  '',
  ...list('base', base),
  '',
  ...list('loose', loose),
  '',
].join(EOL);
const target = path.join(repo, 'gamedata', 'scripts', 'persistent_stalkers_lobby_known.script');
fs.writeFileSync(target, out);
console.log(`${target}: ${base.length} base, ${loose.length} loose`);
