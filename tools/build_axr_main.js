// Builds the lobby's script gate (AGENTS.md, "The lobby", "Scripts not started"):
//
//   gamedata/scripts/axr_main.script            the game's own axr_main.script with
//                                               two marked changes in on_game_start
//   gamedata/scripts/persistent_stalkers_skip.script
//                                               the scripts a lobby game does not start
//
// In a lobby game (the lobby's marker is fresh; persistent_stalkers_lobby.startup_skip)
// axr_main neither loads nor starts the scripts on the skip list, and calls every other
// on_game_start in a pcall. Every other game runs the original code path.
//
// The skip list: every script an enabled Mod Organizer mod ships, except
//   - a name Anomaly itself has (scripts.db0, unpacked: a mod's copy of a base script),
//   - a name loose in D:\Anomaly\gamedata\scripts (xrRazom, the modded exes),
//   - the mods the lobby needs (this one, Master Core, Multiplayer settings, MCM),
//   - names the lobby needs by prefix.
// Anything not known to come from a mod is started as usual.
//
// Run:  node tools/build_axr_main.js [anomaly dir] [mo2 dir] [profile] [unpacked base scripts]
// Again after an update of Anomaly, the modded exes, xrRazom, or the mod list.
'use strict';
const fs = require('fs');
const path = require('path');

const repo = path.resolve(__dirname, '..');
const anomaly = process.argv[2] || 'D:/Anomaly';
const mo2 = process.argv[3] || 'D:/GAMMA';
const profile = process.argv[4] || 'GEM';
const baseDir = process.argv[5] || path.resolve(repo, '..', 'Lobby_spawn', 'anomaly_db', 'scripts');

const KEEP_MODS = [/^Persistent_stalkers$/, /^Master_core$/, /^Multiplayer_settings$/, /MCM/i];
const KEEP_PREFIX = ['persistent_stalkers', 'master_core', 'xrr_', 'ui_mcm', 'modxml_', 'dxml'];

function scripts(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter(f => /\.script$/i.test(f)).map(f => f.toLowerCase());
}

// --- the skip list
if (!fs.existsSync(baseDir)) {
  console.error(`no unpacked base scripts at ${baseDir}\n(converter.exe -unpack -xdb ${anomaly}\\db\\configs\\scripts.db0 -dir <dir>)`);
  process.exit(1);
}
const base = new Set(scripts(baseDir));
const loose = new Set(scripts(path.join(anomaly, 'gamedata', 'scripts')));
const modlist = fs.readFileSync(path.join(mo2, 'profiles', profile, 'modlist.txt'), 'utf8')
  .split(/\r?\n/).filter(l => l.startsWith('+')).map(l => l.slice(1));
const skip = new Map(); // script -> mod
let kept = 0;
for (const mod of modlist) {
  const own = scripts(path.join(mo2, 'mods', mod, 'gamedata', 'scripts'));
  for (const s of own) {
    const name = s.replace(/\.script$/, '');
    if (KEEP_MODS.some(r => r.test(mod)) || base.has(s) || loose.has(s) || KEEP_PREFIX.some(p => name.startsWith(p))) {
      kept++;
      continue;
    }
    if (!skip.has(s)) skip.set(s, mod);
  }
}
// a name kept anywhere is kept (a kept mod or the base may ship the same name)
for (const mod of modlist) {
  if (!KEEP_MODS.some(r => r.test(mod))) continue;
  for (const s of scripts(path.join(mo2, 'mods', mod, 'gamedata', 'scripts'))) skip.delete(s);
}

// xrRazom's patch scripts for skipped mods (user's request, 2026-11-16): each is
// loose in gamedata (kept above), and its on_game_start loads the mod it patches
// (in game: xrr_patch_paw 2.6 s, xrr_patch_pba 0.5 s). A patch is skipped when it
// names a skipped script (as `name.`, `name:`, `name[` or "name") and fewer than
// PATCH_BASE_MAX of Anomaly's own: the broad ones (common, client, quests, ...) stay.
const PATCH_BASE_MAX = 5;
const IGNORE_WORDS = new Set(['string', 'table', 'math', 'level', 'db', 'alife', 'game', 'bit', 'io', 'os']);
const looseDir = path.join(anomaly, 'gamedata', 'scripts');
const patchesSkipped = [];
for (const f of scripts(looseDir).filter(f => /^xrr_patch_/.test(f))) {
  const src = fs.readFileSync(path.join(looseDir, f), 'utf8').replace(/--[^\n]*/g, '');
  const named = new Set();
  for (const m of src.matchAll(/\b([A-Za-z_][A-Za-z0-9_]*)\s*[.:\[]/g)) named.add(m[1].toLowerCase());
  for (const m of src.matchAll(/["']([A-Za-z_][A-Za-z0-9_]*)["']/g)) named.add(m[1].toLowerCase());
  const mods = [...named].filter(n => skip.has(n + '.script'));
  const bases = [...named].filter(n => base.has(n + '.script') && !IGNORE_WORDS.has(n));
  if (mods.length > 0 && bases.length < PATCH_BASE_MAX) {
    skip.set(f, `xrRazom patch for ${mods.slice(0, 3).join(', ')}`);
    patchesSkipped.push(f.replace(/\.script$/, ''));
  }
}

const EOL = '\r\n';
const names = [...skip.keys()].sort();
let out = [
  '-- Generated by tools/build_axr_main.js: do not edit. The scripts a lobby game',
  '-- does not load or start (persistent_stalkers_lobby.startup_skip): every script',
  `-- an enabled mod ships that is not Anomaly's own, loose in gamedata, or one the lobby needs.`,
  `-- ${names.length} scripts, from the ${profile} profile.`,
  '',
  'names = {',
  ...names.map(n => `\t["${n}"] = true, -- ${skip.get(n)}`),
  '}',
  '',
].join(EOL);
fs.writeFileSync(path.join(repo, 'gamedata', 'scripts', 'persistent_stalkers_skip.script'), out);

// --- axr_main.script
const srcPath = path.join(anomaly, 'gamedata', 'scripts', 'axr_main.script');
let src = fs.readFileSync(srcPath, 'utf8');
const eol = src.includes('\r\n') ? '\r\n' : '\n';
function patch(re, fn, what) {
  const m = src.match(new RegExp(re.source, 'g'));
  if (!m || m.length !== 1) {
    console.error(`axr_main.script: the ${what} was found ${m ? m.length : 0} times, not once: the file changed, the patch needs a look`);
    process.exit(1);
  }
  src = src.replace(re, fn);
}
// 1. the skip list, decided once before the scripts are listed
patch(/(\n)(\tlocal t = \{\}\r?\n\tlocal size_t = 0 *\r?\n)/, (_, nl, rest) => nl + [
  '\t-- Persistent Stalkers (tools/build_axr_main.js): in a lobby game the scripts',
  '\t-- on persistent_stalkers_skip are not loaded or started, and every other',
  '\t-- on_game_start runs in a pcall. Any other game: pst_skip is nil, the code below as it was.',
  '\tlocal pst_skip = nil',
  '\tdo',
  '\t\tlocal ok, s = pcall(function() return persistent_stalkers_lobby.startup_skip() end)',
  '\t\tif ok and type(s) == "table" then pst_skip = s end',
  '\tend',
  '\t-- and times each script then (persistent_stalkers_lobby.startup_report)',
  '\tlocal pst_clock = pst_skip and os and os.clock',
  '\tlocal pst_load, pst_start = {}, {}',
  '',
].join(eol) + eol + rest, 'start of the script list');
// 2. a skipped script is neither loaded (_G[file_name]) nor started
patch(/if \(file:Size\(\) > 0 and ignore\[file_name\] ~= true\) then/,
  () => 'if (file:Size() > 0 and ignore[file_name] ~= true and not (pst_skip and pst_skip[string.lower(file_name)])) then -- Persistent Stalkers',
  'script filter');
// 3. the time a script's file takes when it is first named (lobby only)
patch(/(\t+)if \(_G\[file_name\] and _G\[file_name\]\.on_game_start\) then/, (_, ind) => [
  `${ind}local pst_t0 = pst_clock and pst_clock() -- Persistent Stalkers`,
  `${ind}local pst_m = _G[file_name]`,
  `${ind}if pst_t0 then pst_load[file_name] = pst_clock() - pst_t0 end`,
  `${ind}if (pst_m and pst_m.on_game_start) then`,
].join(eol), 'script load check');
// 4. in a lobby game one failing on_game_start does not stop the others; each is timed, then reported
patch(/(\t+)_G\[ t\[i\] \]\.on_game_start\(\)(\r?\n\tend)/, (_, ind, loopEnd) => [
  `${ind}if pst_skip then -- Persistent Stalkers`,
  `${ind}\tlocal pst_t0 = pst_clock and pst_clock()`,
  `${ind}\tlocal ok, err = pcall(_G[ t[i] ].on_game_start)`,
  `${ind}\tif pst_t0 then pst_start[t[i]] = pst_clock() - pst_t0 end`,
  `${ind}\tif not ok then printf("![PersistentStalkers] lobby: on_game_start of %s failed: %s", t[i], tostring(err)) end`,
  `${ind}else`,
  `${ind}\t_G[ t[i] ].on_game_start()`,
  `${ind}end`,
].join(eol) + loopEnd + eol + [
  '\tif pst_clock then -- Persistent Stalkers',
  '\t\tpcall(function() persistent_stalkers_lobby.startup_report(pst_load, pst_start) end)',
  '\tend',
].join(eol), 'on_game_start call');
fs.writeFileSync(path.join(repo, 'gamedata', 'scripts', 'axr_main.script'), src);

console.log(`skip list: ${names.length} scripts (${kept} mod scripts kept), ${patchesSkipped.length} of them xrRazom patches: ${patchesSkipped.join(' ')}; axr_main.script patched from ${srcPath}`);
